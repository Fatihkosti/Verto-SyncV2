/**
 * B09 shared, lossless financial mapping. Producer and REMOTE_APPLY use the same DTO fields.
 * Minor values are authoritative. Compatibility doubles are derived once, never read back.
 * Attachment URIs and dirty flags are local metadata, not fields trusted from the network.
 */
fun InvoiceEntity.toDtoV2() = InvoiceDtoV2(
    id = id,
    invoiceNumber = invoiceNumber,
    clientId = clientId,
    organizationId = organizationId,
    supplierInvoiceReference = supplierInvoiceReference,
    supplierInvoiceReferenceNormalized = supplierInvoiceReferenceNormalized,
    type = type.name,
    category = category.name,
    description = description,
    totalAmountMinor = totalAmountMinor,
    transactionCurrencyCode = transactionCurrencyCode,
    functionalCurrencyCode = functionalCurrencyCode,
    transactionAmountMinor = transactionAmountMinor,
    invoiceExchangeRateSnapshot = invoiceExchangeRateSnapshot,
    exchangeRateDirection = exchangeRateDirection,
    exchangeRateTimestamp = exchangeRateTimestamp,
    exchangeRateSource = exchangeRateSource,
    functionalAmountAtRecognitionMinor = functionalAmountAtRecognitionMinor,
    legacyCurrencyStatus = legacyCurrencyStatus.name,
    createdAt = createdAt,
    dueDate = dueDate,
    notifyDaysBefore = notifyDaysBefore,
    notifyRepeatDays = notifyRepeatDays,
    notificationsEnabled = notificationsEnabled,
    notes = notes,
    isOwedToMe = isOwedToMe,
    status = status.name,
    discountMinor = discountMinor,
    commissionMinor = commissionMinor,
    commissionBeneficiaryClientId = commissionBeneficiaryClientId,
    commissionSource = commissionSource,
    shipmentId = shipmentId,
    purchaseOrderId = purchaseOrderId,
    purchaseScope = purchaseScope.name,
    createdBy = createdBy,
    lifecycleStatus = lifecycleStatus.name,
    lifecycleVersion = lifecycleVersion,
    postedAt = postedAt,
    voidedAt = voidedAt,
    voidReason = voidReason,
    voidWriteId = voidWriteId,
)

