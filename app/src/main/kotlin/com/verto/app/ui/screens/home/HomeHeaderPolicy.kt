internal fun homeHeaderPeriodFor(time: LocalTime): HomeHeaderPeriod = when {
    time >= LocalTime.of(4, 0) && time < LocalTime.NOON -> HomeHeaderPeriod.MORNING
    time >= LocalTime.NOON && time < LocalTime.of(16, 0) -> HomeHeaderPeriod.DAY
    else -> HomeHeaderPeriod.EVENING
}

internal fun homeHeaderMessageIndex(date: LocalDate): Int =
    Math.floorMod(date.toEpochDay(), HomeHeaderMessages.morning.size.toLong()).toInt()

internal fun homeHeaderCopyFor(dateTime: LocalDateTime): HomeHeaderCopy {
    val period = homeHeaderPeriodFor(dateTime.toLocalTime())
    val phrase = HomeHeaderMessages.forPeriod(period)[homeHeaderMessageIndex(dateTime.toLocalDate())]
    val greeting = when (period) {
        HomeHeaderPeriod.MORNING -> "صباح الخير"
        HomeHeaderPeriod.DAY -> "نهارك سعيد"
        HomeHeaderPeriod.EVENING -> "مساء الخير"
    }
    return HomeHeaderCopy(greeting = greeting, phrase = phrase)
}

internal fun nextHomeHeaderBoundary(now: ZonedDateTime): ZonedDateTime {
    val zone = now.zone
    val date = now.toLocalDate()
    val candidates = listOf(
        LocalTime.MIDNIGHT,
        LocalTime.of(4, 0),
        LocalTime.NOON,
        LocalTime.of(16, 0),
    ).map { time -> ZonedDateTime.of(date, time, zone) }
    return candidates.firstOrNull { it.isAfter(now) }
        ?: ZonedDateTime.of(date.plusDays(1), LocalTime.MIDNIGHT, zone)
}

internal fun homeDisplayName(userName: String): String =
